const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawn } = require('node:child_process');
const { once } = require('node:events');
const root = path.resolve(__dirname, '..');
const out = path.join(root, 'test-artifacts', 'mouse-audit');
fs.mkdirSync(out, { recursive: true });
let server, browser, page;
const errors = [];

async function main() {
  server = spawn(process.execPath, ['server.js'], { cwd: root, windowsHide: true,
    env: { ...process.env, PORT: '0', DATABASE_URL: '', SA_LOCAL_DATA_DIR: fs.mkdtempSync(path.join(os.tmpdir(), 'sa-mouse-audit-')) }, stdio: ['ignore', 'pipe', 'pipe'] });
  const base = await new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(Error('Server startup timed out')), 10000);
    server.on('error', reject);
    server.stdout.on('data', chunk => { const url = String(chunk).match(/Local:\s+(http:\/\/127\.0\.0\.1:\d+)/)?.[1]; if (url) { clearTimeout(timer); resolve(url); } });
  });
  const post = async (route, body) => {
    const response = await fetch(base + '/api/' + route, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
    const result = await response.json(); assert.ok(response.ok, JSON.stringify(result)); return result;
  };
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext({ viewport: { width: 1366, height: 768 } });
  context.on('page', p => p.on('pageerror', e => errors.push(e.message)));
  page = await context.newPage();
  const created = page.waitForResponse(r => r.url().endsWith('/api/campaign/showcase/start'));
  await page.goto(base + '/showcase.html');
  const room = await (await created).json();
  const gm = page.frameLocator('#showcaseFrame');
  await gm.locator('#campaignCodeHeading').filter({ hasText: room.code }).waitFor();
  await gm.locator('#scriptTab').waitFor();
  await page.getByRole('button', { name: 'Nova Vale', exact: true }).click();
  const pc = page.frameLocator('#showcaseFrame');
  await pc.locator('[data-character-tab=roster].active').waitFor();
  await page.reload();
  await pc.locator('[data-character-tab=roster].active').waitFor();
  assert.ok((await page.locator('#showcaseFrame').getAttribute('src')).includes(room.code), 'Reload keeps the same room');
  await pc.getByRole('button', { name: 'Starships', exact: true }).click();
  const ship = pc.frameLocator('[data-player-ship-details]');
  await ship.getByRole('button', { name: 'Toggle Console', exact: true }).click();
  await page.locator('.interface-notice:popover-open').filter({ hasText: 'Move onto a station' }).waitFor();
  const noticeBox = await page.locator('.interface-notice').boundingBox();
  assert.ok(noticeBox.y >= 0 && noticeBox.y + noticeBox.height <= 768, 'Feedback is visible while the ship sheet is scrolled');
  await page.screenshot({ path: path.join(out, 'visible-map-feedback.png') });
  await page.getByRole('button', { name: 'Dismiss notification', exact: true }).click();
  for (const key of ['labels', 'highResolution', 'combatMesh', 'walls', 'stations', 'hull']) {
    const toggle = ship.locator(`.desktop-map-display [data-map-display="${key}"]`);
    const before = await toggle.isChecked();
    await toggle.locator('..').click(); assert.equal(await toggle.isChecked(), !before);
    await toggle.locator('..').click(); assert.equal(await toggle.isChecked(), before);
  }
  await ship.getByRole('button', { name: 'Move', exact: true }).click();
  await ship.locator('.embedded-move-controls [data-action=cancel]').first().waitFor();
  await ship.locator('.ship-grid:not(.mobile-grid) [data-grid-index="149"]').click({ position: { x: 8, y: 8 } });
  await ship.locator('.embedded-move-controls [data-action=confirm]').first().filter({ hasText: 'Station' }).click();
  await ship.getByRole('button', { name: 'Move', exact: true }).waitFor();
  await ship.getByRole('button', { name: 'Toggle Console', exact: true }).click();
  await page.getByRole('dialog', { name: 'Pilot console', exact: true }).waitFor();
  await page.locator('[data-command-status]').filter({ hasText: 'OUT OF COMBAT' }).waitFor();
  await page.locator('.station-console-select').selectOption('showcase-pc-ship-sensors');
  const sensors = page.getByRole('dialog', { name: 'Sensor console', exact: true });
  await sensors.waitFor(); await page.waitForTimeout(1300);
  await sensors.locator('[data-turn]').filter({ hasText: 'OUT OF COMBAT' }).waitFor();
  const beforeZoom = await sensors.locator('[data-space-canvas]').getAttribute('viewBox');
  await sensors.getByRole('button', { name: 'Zoom in', exact: true }).click();
  assert.notEqual(await sensors.locator('[data-space-canvas]').getAttribute('viewBox'), beforeZoom);
  assert.equal(await sensors.locator('[data-order=area]').isDisabled(), true);
  assert.equal(await sensors.locator('[data-action-help]').first().isEnabled(), true);
  await sensors.locator('[data-action-help]').first().click();
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.screenshot({ path: path.join(out, 'sensors-laptop.png') });
  await sensors.getByRole('button', { name: 'Close Console', exact: true }).click();
  await page.getByRole('button', { name: 'GM', exact: true }).click();
  await gm.locator('#exitEncounter').click();
  await gm.locator('[data-encounter-mode=starship]').click();
  await gm.locator('[data-encounter-starship="showcase-pc-ship"]').check();
  await gm.locator('[data-encounter-starship="showcase-npc-ship"]').check();
  const editor = gm.locator('[data-encounter-space-map]');
  await editor.scrollIntoViewIfNeeded();
  const bothVisible = await editor.locator('svg').evaluate(svg => [...svg.querySelectorAll('[data-space-ship]')].every(marker => {
    const p = marker.transform.baseVal.consolidate().matrix, v = svg.viewBox.baseVal;
    return p.e >= v.x && p.e <= v.x + v.width && p.f >= v.y && p.f <= v.y + v.height;
  }));
  assert.ok(bothVisible, 'Both selected ships are in the initial preparation view');
  await editor.locator('[data-prep-zoom]').last().click();
  const zoomBox = await editor.locator('svg').getAttribute('viewBox');
  await editor.locator('[data-space-axis=q]').last().fill('20');
  await editor.locator('[data-space-axis=q]').last().press('Tab');
  assert.equal(await editor.locator('svg').getAttribute('viewBox'), zoomBox, 'Editing a position preserves manual zoom');
  await page.screenshot({ path: path.join(out, 'prepare-both-ships.png') });
  await gm.locator('#beginEncounter').click();
  await gm.frameLocator('#atbFrame').getByRole('button', { name: 'Engage Clock', exact: true }).waitFor();
  const clockBox = await gm.frameLocator('#atbFrame').getByRole('button', { name: 'Engage Clock', exact: true }).boundingBox();
  assert.ok(clockBox.y >= 0 && clockBox.y + clockBox.height < 768, 'Combat opens at its clock controls');

  // Create a permanent room through the GM form; use a fixture only for character entry.
  const realGm = await context.newPage(); await realGm.goto(base + '/gm.html');
  await realGm.getByRole('button', { name: 'Create Campaign', exact: true }).click();
  await realGm.locator('#newCampaignName').fill('Mouse Audit Campaign');
  await realGm.locator('#newCampaignPassword').fill('audit-gm');
  await realGm.locator('#confirmCampaignPassword').fill('audit-gm');
  const realCreated = realGm.waitForResponse(r => r.url().endsWith('/api/campaign/create'));
  await realGm.getByRole('button', { name: 'Create Permanent Campaign', exact: true }).click();
  const realRoom = await (await realCreated).json();
  const code = realRoom.campaign.code, token = realRoom.token;
  const fixture = { id: 'audit-pc', phase: 'finalized', access: { pcCode: 'audit-pc' }, identity: { characterName: 'Audit Pilot', playerName: 'Player' }, attributes: { health: [1,0,-1,-1], intellect: [1,0,-1,-1], dexterity: [1,0,-1,-1] }, computed: { maximumHp: 30, moveSpeed: 3, speed: 8, commandWindow: 60, skills: {} }, health: { current: 30 } };
  const join = await post('campaign/join/request', { code, character: fixture });
  await post('campaign/join/respond', { code, token, requestId: join.requestId, decision: 'approve' });
  const demoState = await fetch(`${base}/api/campaign/state?code=${room.code}&token=${room.gmToken}`).then(r => r.json());
  const demoShip = demoState.starships[0];
  await post('campaign/starship/link', { code, token, starship: { ...demoShip.ship, id: 'audit-ship', title: 'Audit Ship' } });
  await post('campaign/starship/crew', { code, token, starshipId: 'audit-ship', crewCharacterIds: [fixture.id] });
  const playerContext = await browser.newContext({ viewport: { width: 1366, height: 768 } });
  const player = await playerContext.newPage(); player.on('pageerror', e => errors.push(e.message));
  await player.goto(`${base}/character.html?campaign=${code}&character=${fixture.id}`);
  await player.getByRole('button', { name: 'Enter PC Code', exact: true }).click();
  await player.getByRole('textbox', { name: 'Enter PC Code', exact: true }).fill('audit-pc');
  await player.getByRole('button', { name: 'Unlock Character', exact: true }).click();
  await player.getByRole('button', { name: 'Starships', exact: true }).click();
  const realShip = player.frameLocator('[data-player-ship-details]');
  await realShip.locator('.desktop-map-display').waitFor();
  assert.equal(await realShip.locator('.desktop-map-display [data-map-display]').count(), 6);
  await player.getByRole('button', { name: 'Upgrade Ship', exact: true }).waitFor();
  for (const name of ['Move', 'Console View', 'System Repairs and Diagnostics', 'Print Starship']) await realShip.getByRole('button', { name, exact: true }).waitFor();
  await realShip.getByRole('button', { name: 'Toggle Console', exact: true }).click();
  await player.locator('.interface-notice:popover-open').waitFor();
  await player.screenshot({ path: path.join(out, 'independent-player-room.png') });
  const demoContext = await browser.newContext();
  const demoPlayer = await demoContext.newPage();
  await demoPlayer.goto(`${base}/character.html?campaign=${room.code}&character=${room.players[0].id}`);
  assert.equal(new URL(demoPlayer.url()).searchParams.get('showcase'), '1');
  await demoPlayer.getByRole('button', { name: 'Character Sheet', exact: true }).click();
  await demoPlayer.getByRole('button', { name: 'Enter PC Code', exact: true }).click();
  await demoPlayer.getByRole('textbox', { name: 'Enter PC Code', exact: true }).fill(demoState.characters[0].pcCode);
  await demoPlayer.getByRole('button', { name: 'Unlock Character', exact: true }).click();
  await demoPlayer.getByRole('button', { name: 'Starships', exact: true }).click();
  await demoPlayer.frameLocator('[data-player-ship-details]').locator('.desktop-map-display').waitFor();
  assert.deepEqual(await demoPlayer.evaluate(() => [localStorage.getItem('sa2e-character-library-v1'), localStorage.getItem('sa-character-campaign-code')]), [null, null], 'Direct demo room access never writes personal saves');
  await page.getByRole('button', { name: 'Reset Room', exact: true }).click();
  await gm.locator('#campaignCodeHeading').filter({ hasNotText: room.code }).waitFor();
  assert.equal(await page.evaluate(key => sessionStorage.getItem(key), `sa-gm-token-${room.code}`), null);
  assert.deepEqual(errors, []);
  console.log('PASS: Explore reload/reset, visible notices, six map toggles, walking/station access, Sensors zoom/help, preparation fit/manual zoom/scroll, real room creation and independent PC access parity.');
}
main().catch(async error => { console.error(error); await page?.screenshot({ path: path.join(out, 'failure.png') }).catch(() => {}); process.exitCode = 1; })
  .finally(async () => { await browser?.close(); if (server && server.exitCode === null) { const stopped = once(server, 'exit'); server.kill(); await stopped; } });
